test("ett fält flyttas när kunden väljer en annan kolumn; e-post och telefon får flera", () => {
  const val: Kolumnval[] = ["company_name", "contact_email", "hoppa", "contact_phone"];
  assert.deepEqual(bytKolumnval(val, 2, "company_name"), ["hoppa", "contact_email", "company_name", "contact_phone"]);
  assert.deepEqual(bytKolumnval(val, 2, "contact_email"), ["company_name", "contact_email", "contact_email", "contact_phone"]);
  assert.deepEqual(bytKolumnval(val, 0, "extra"), ["extra", "contact_email", "hoppa", "contact_phone"]);
});
