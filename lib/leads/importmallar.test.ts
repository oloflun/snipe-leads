test("värden som inte håller anmärks och lämnas tomma, raden importeras", () => {
  // Kolumnvalet är kundens eget här: radbyggaren prövas för sig.
  const tabell = tolkaTabell(parseCsv("Bolag;Org.nr;E-post;Telefon;Hemsida;Avtalsslut\nAlfa Test AB;811218-9876;eva(at)example.se;4,67E+10;eva@example.se;snart\n"));
  const utfall = tolkaRader(tabell, ["company_name", "orgnr", "contact_email", "contact_phone", "website", "avtalsslut"]);
  assert.deepEqual(utfall[0].rad, { company_name: "Alfa Test AB" });
  assert.deepEqual(
    utfall[0].anmarkningar.map((a) => [a.falt, a.kod]),
    [
      ["orgnr", "personnummer"],
      ["contact_email", "epost"],
      ["contact_phone", "excel"],
      ["website", "webb"],
      ["avtalsslut", "datum"]
    ]
  );
});

test("ett bolag, en rad: raden med adress är den som importeras", () => {
  const { utfall, rader } = las(
    "Bolag;Org.nr;Kontakt;E-post;Telefon\nAlfa Test AB;569900-1219;Per Ek;;08-465 004 01\nALFA TEST AKTIEBOLAG;;Eva Ek;eva@example.se;\nBeta Test AB;569900-1227;Åsa Ek;asa@example.se;\nAlfa Test (publ);5699001219;Ola Ek;;\n;;Utan Bolag;x@example.se;\n"
  );
  assert.deepEqual(rader.map((r) => [r.company_name, r.contact_name]), [
    ["ALFA TEST AKTIEBOLAG", "Eva Ek"],
    ["Beta Test AB", "Åsa Ek"]
  ]);
  assert.deepEqual(utfall.map((u) => u.dubblettAv), [1, undefined, undefined, 1, undefined]);
  const s = sammanfatta(utfall);
  assert.deepEqual([s.rader, s.importeras, s.dubbletter, s.utanBolag, s.medEpost], [5, 2, 2, 1, 2]);
});

