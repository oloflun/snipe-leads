test("Namn är bolaget i ett kundregister och personen i en kontaktexport", () => {
  assert.equal(las("Namn;Organisationsnummer;Telefon\nAlfa Test AB;569900-1219;08-465 004 01\n").karta.Namn, "company_name");
  assert.equal(las("Organisation;Namn;E-post\nAlfa Test AB;Eva Ek;eva@example.se\n").karta.Namn, "contact_name");
  const dubbla = las("Namn;Org.nr;Namn;E-post\nAlfa Test AB;569900-1219;Eva Ek;eva@example.se\n");
  assert.deepEqual(dubbla.tabell.rubriker, ["Namn", "Org.nr", "Namn (2)", "E-post"]);
  assert.deepEqual(dubbla.rader, [{ company_name: "Alfa Test AB", orgnr: "569900-1219", contact_name: "Eva Ek", contact_email: "eva@example.se" }]);
});

